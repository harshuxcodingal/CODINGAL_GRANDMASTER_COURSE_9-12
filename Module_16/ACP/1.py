# Mean, Median, Mode

import statistics

# Data
data = [10, 20, 30, 40, 50, 20]

# Mean
mean = statistics.mean(data)

# Median
median = statistics.median(data)

# Mode
mode = statistics.mode(data)

# Display Results
print("Data:", data)
print("Mean =", mean)
print("Median =", median)
print("Mode =", mode)