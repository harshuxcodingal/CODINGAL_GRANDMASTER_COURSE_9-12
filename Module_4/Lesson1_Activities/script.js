// Variables
let studentName = "Harshal";
let age = 25;
let percentage = 85.5;
let isPassed = true;

// Statements
console.log("Student Name:", studentName);
console.log("Age:", age);
console.log("Percentage:", percentage);
console.log("Passed:", isPassed);

// Values and Data Types
console.log("Type of studentName:", typeof studentName);
console.log("Type of age:", typeof age);
console.log("Type of percentage:", typeof percentage);
console.log("Type of isPassed:", typeof isPassed);

// Arithmetic Operators
let a = 20;
let b = 10;

console.log("Addition:", a + b);
console.log("Subtraction:", a - b);
console.log("Multiplication:", a * b);
console.log("Division:", a / b);
console.log("Modulus:", a % b);

// Comparison Operators
console.log("a > b :", a > b);
console.log("a < b :", a < b);
console.log("a == b :", a == b);
console.log("a != b :", a != b);

// Logical Operators
console.log("a > 15 && b < 15 :", a > 15 && b < 15);
console.log("a > 25 || b < 15 :", a > 25 || b < 15);
console.log("!(a > b) :", !(a > b));

// Conditional Statement
if (percentage >= 80) {
    console.log("Grade: A");
} else {
    console.log("Grade: B");
}

// End of Program
console.log("JavaScript Basics Completed!");