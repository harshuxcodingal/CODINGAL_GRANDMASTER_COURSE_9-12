# Operations using NumPy

import numpy as np

# Create NumPy arrays
a = np.array([10, 20, 30, 40, 50])
b = np.array([1, 2, 3, 4, 5])

# Addition
print("Addition:", a + b)

# Subtraction
print("Subtraction:", a - b)

# Multiplication
print("Multiplication:", a * b)

# Division
print("Division:", a / b)

# Mean
print("Mean of a:", np.mean(a))

# Maximum value
print("Maximum value:", np.max(a))

# Minimum value
print("Minimum value:", np.min(a))

# Sum of elements
print("Sum:", np.sum(a))